# RAG PIPELINE
# ============================================================

def load_rag_components():

    print("Loading RAG components...")

    vectorstore = load_vectorstore()

    documents = load_documents()

    bm25 = build_bm25(documents)

    reranker = load_reranker()

    llm = load_llm()

    print("All RAG components loaded successfully.")

    return {
        "vectorstore": vectorstore,
        "documents": documents,
        "bm25": bm25,
        "reranker": reranker,
        "llm": llm,
    }


def ask_rag(
    components,
    query: str,
):
    """
    Run the complete RAG pipeline.

    Question
        ↓
    Hybrid Retrieval
        ↓
    RRF
        ↓
    Reranking
        ↓
    Context Building
        ↓
    Gemini
        ↓
    Answer
    """

    if not query.strip():
        raise ValueError("Query cannot be empty.")

    # --------------------------------------------------------
    # 1. Hybrid Retrieval
    # --------------------------------------------------------

    candidates = hybrid_retrieve(
        vectorstore=components["vectorstore"],
        bm25=components["bm25"],
        documents=components["documents"],
        query=query,
        k=10,
        dense_k=10,
        bm25_k=10,
    )

    # --------------------------------------------------------
    # 2. Reranking
    # --------------------------------------------------------

    pairs = [
        [query, candidate["document"].page_content]
        for candidate in candidates
    ]

    reranker_scores = components["reranker"].predict(pairs)

    scored_candidates = []

    for candidate, score in zip(candidates, reranker_scores):

        result = candidate.copy()

        result["reranker_score"] = float(score)

        scored_candidates.append(result)

    scored_candidates.sort(
        key=lambda result: result["reranker_score"],
        reverse=True,
    )

    final_results = scored_candidates[:5]

    # --------------------------------------------------------
    # 3. Build Context
    # --------------------------------------------------------

    context = build_context(
        final_results,
        max_chars=12000,
    )

    # --------------------------------------------------------
    # 4. Generate Answer
    # --------------------------------------------------------

    answer = generate_answer(
        llm=components["llm"],
        query=query,
        context=context,
    )

    return {
        "answer": answer,
        "sources": final_results,
    }



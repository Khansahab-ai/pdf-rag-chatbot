# ============================================================
# BUILD MESSAGES
# ============================================================

def build_messages(query: str, context: str):
    """
    Build the messages that will be sent to the LLM.

    Parameters
    ----------
    query : str
        The user's question.

    context : str
        The retrieved document context created by context_builder.py.

    Returns
    -------
    list
        LangChain messages containing:
        - system instructions
        - user question
        - document context
    """

    system_message = SystemMessage(
        content=SYSTEM_PROMPT
    )

    human_message = HumanMessage(
        content=f"""
QUESTION:

{query}


DOCUMENT CONTEXT:

{context}


ANSWER:
"""
    )

    return [
        system_message,
        human_message,
    ]


# ============================================================
# GENERATE ANSWER
# ============================================================

def generate_answer(llm, query: str, context: str) -> str:
    """
    Generate an answer using any LangChain-compatible chat model.

    Example models that can later be passed here:

    ChatOpenAI
    ChatGoogleGenerativeAI
    ChatOllama
    etc.

    Parameters
    ----------
    llm
        A LangChain-compatible chat model.

    query : str
        User question.

    context : str
        Context produced by context_builder.py.

    Returns
    -------
    str
        Final answer generated by the model.
    """

    if not query.strip():
        raise ValueError("Query cannot be empty.")

    if not context.strip():
        return (
            "The provided document context does not contain enough "
            "information to answer this question."
        )

    messages = build_messages(
        query=query,
        context=context,
    )

    response = llm.invoke(messages)

    content = response.content

    if isinstance(content, list):
        text_parts = []

        for item in content:
            if isinstance(item, dict) and item.get("type") == "text":
                text_parts.append(item.get("text", ""))

        return "\n".join(text_parts).strip()

    return str(content).strip()


def load_llm():
    """
    Create and return the Gemini chat model.
    """

    llm = ChatGoogleGenerativeAI(
        model="gemini-3.5-flash",
        temperature=0,
    )

    print("Gemini LLM loaded successfully.")

    return llm

